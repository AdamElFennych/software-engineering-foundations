// * Types of Inheritance (These 3 are used in most programming languages):
//
// * 1. Single Inheritance: 
// * Example clsB inherits from clsA.
//
// * 2. Multi-Level Inheritance: 
// * Example clsC inherits from clsB, which inherits from clsA.
//
// * 3. Hierarchical Inheritance: 
// * Example clsB, clsC, and clsD all inherit from clsA.
//
// ! Additional types of Inheritance found only in C++ (Using them may cause problems in the program):
//
// ! ☒ Multiple Inheritance: 
// ! Example clsC inherits from two – clsA and clsB.
//
// ! ☒ Hybrid Inheritance: 
// ! Example clsD inherits from two – clsB and clsC, and both of them inherit from clsA.
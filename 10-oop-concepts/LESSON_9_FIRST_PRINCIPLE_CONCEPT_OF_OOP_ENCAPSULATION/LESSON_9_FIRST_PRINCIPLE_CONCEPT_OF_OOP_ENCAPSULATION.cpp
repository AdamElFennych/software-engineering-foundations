// Based on what we learned in previous lessons:
// - A class is a category that contains everything related to it.
// - Encapsulation is the process of grouping:
//   - Variables,
//   - Procedures,
//   - and functions
//   that are related to this class.
//
// Concept:
// - The word "Encapsulation" is derived from a medicinal capsule.
//
// Function:
// - A class gathers all related methods under one roof.
//
// Components:
// - Methods: known as member methods (functions).
// - Data members: known as variables.
//
// Goal:
// - You cannot access these members from outside the class except through an object.
// - This is related to the property of data hiding.
